"""Refreshes the "Latest finds" teaser on the home page.

Reads the finds list kept in the Barcoded Stamps site
(modern-gb-stamp-decoder/website/src/content/latest-finds.json) and rewrites
the block between the FINDS markers in index.html. Run it after new finds are
published there:  python3 update-finds.py
"""
import html
import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).parent
SOURCE = ROOT.parent / "modern-gb-stamp-decoder/website/src/content/latest-finds.json"
COPY = ROOT / "assets/latest-finds.json"
SHOW = 3
BASE = "https://barcodedstamps.com/latest-finds/"
STATUS = {
    "reported": "Reported",
    "corroborated": "Corroborated",
    "catalogued": "Catalogued",
    "available_in_app": "Available in app",
}

if SOURCE.exists():
    COPY.write_text(SOURCE.read_text())
finds = json.loads(COPY.read_text())
finds.sort(key=lambda f: f["id"])
finds.sort(key=lambda f: f["publishedAt"], reverse=True)


def nice(d):
    y, m, dd = map(int, d.split("-"))
    return date(y, m, dd).strftime("%-d %b %Y")


items = []
for f in finds[:SHOW]:
    e = html.escape
    items.append(
        f'''      <li class="find">
        <a href="{BASE}#{e(f["id"])}">
          <span class="find-meta"><time datetime="{e(f["publishedAt"])}">{nice(f["publishedAt"])}</time><span class="find-status">{e(STATUS.get(f["status"], f["status"]))}</span></span>
          <strong>{e(f["title"])}</strong>
          <span class="find-detail">{e(f["encodedValue"])} · {e(f["sourceFormat"])}</span>
        </a>
      </li>'''
    )

block = f'''<!-- FINDS:START (generated by update-finds.py) -->
<section class="finds-section" id="latest-finds">
  <div class="wrap">
    <div class="section-head">
      <span class="kicker">Latest finds</span>
      <h2>New printings, reported by collectors.</h2>
      <p>App users tell us when they scan a stamp the catalogue doesn't have yet. We check each report, then add it to the catalogue and the app.</p>
    </div>
    <ul class="finds">
{chr(10).join(items)}
    </ul>
    <p class="finds-more"><a href="{BASE}">See all latest finds on barcodedstamps.com</a></p>
  </div>
</section>
<!-- FINDS:END -->'''

page = (ROOT / "index.html").read_text()
page, n = re.subn(r"<!-- FINDS:START.*?<!-- FINDS:END -->", lambda _: block, page, flags=re.S)
if n != 1:
    raise SystemExit("FINDS markers not found in index.html")
(ROOT / "index.html").write_text(page)
print(f"index.html updated with {min(SHOW, len(finds))} finds")
